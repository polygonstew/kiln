#!/usr/bin/env python3
"""Convert BDF bitmap fonts to static/js/fonts.js (ASCII 32..126).
Each glyph: [advance, rows...] where rows are cellH ints, bit (cellW-1-x) = pixel x set."""
import json, sys
from pathlib import Path

FONTS = [('tiny', 'Tom Thumb 4×6', 'tom-thumb.bdf'), ('small', 'Spleen 5×8', 'spleen-5x8.bdf'),
         ('body', 'Spleen 6×12', 'spleen-6x12.bdf'), ('large', 'Spleen 8×16', 'spleen-8x16.bdf')]


def parse(fp):
    lines = Path(fp).read_text(errors='replace').splitlines()
    fb = asc = desc = None
    glyphs, i = {}, 0
    while i < len(lines):
        l = lines[i].split()
        if not l:
            i += 1; continue
        if l[0] == 'FONTBOUNDINGBOX':
            fb = list(map(int, l[1:5]))
        elif l[0] == 'FONT_ASCENT':
            asc = int(l[1])
        elif l[0] == 'FONT_DESCENT':
            desc = int(l[1])
        elif l[0] == 'STARTCHAR':
            enc = dw = bbx = None; bm = []
            while True:
                i += 1; l = lines[i].split()
                if l[0] == 'ENCODING': enc = int(l[1])
                elif l[0] == 'DWIDTH': dw = int(l[1])
                elif l[0] == 'BBX': bbx = list(map(int, l[1:5]))
                elif l[0] == 'BITMAP':
                    while True:
                        i += 1
                        if lines[i].strip() == 'ENDCHAR': break
                        bm.append(lines[i].strip())
                    break
            glyphs[enc] = (dw, bbx, bm)
        i += 1
    if asc is None: asc, desc = fb[1] + fb[3], -fb[3]
    return fb, asc, desc, glyphs


out = {}
src = Path(sys.argv[1])
for key, label, fn in FONTS:
    fb, asc, desc, gl = parse(src / fn)
    cw, ch = fb[0], asc + desc
    g = {}
    for c in range(32, 127):
        if c not in gl: continue
        dw, (bw, bh, bx, by), bm = gl[c]
        rows = [0] * ch
        for r, hx in enumerate(bm):
            bits = int(hx, 16); nb = len(hx) * 4
            y = asc - (by + bh) + r
            if not 0 <= y < ch: continue
            for x in range(bw):
                if bits >> (nb - 1 - x) & 1:
                    px = bx + x
                    if 0 <= px < cw: rows[y] |= 1 << (cw - 1 - px)
        g[chr(c)] = [dw] + rows
    out[key] = {'label': label, 'w': cw, 'h': ch, 'base': asc, 'glyphs': g}
Path(sys.argv[2]).write_text('// generated by tools/bdf2js.py from vendor/fonts (Spleen: BSD-2, Tom Thumb: MIT)\nexport const FONTS = ' + json.dumps(out, separators=(',', ':')) + ';\n')
print({k: (v['w'], v['h'], len(v['glyphs'])) for k, v in out.items()})
